/**
 * Test button listeners and interactions across all views
 */
const fs = require('fs');
const path = require('path');

const htmlContent = fs.readFileSync(path.join(__dirname, '../frontend/index.html'), 'utf8');
const jsContent = fs.readFileSync(path.join(__dirname, '../frontend/js/app.js'), 'utf8');

console.log('--- HAPS Scholar Assistant Button Audit ---');

// Parse all button IDs and classes from index.html
const buttonRegex = /<button[^>]*>/gi;
const buttons = htmlContent.match(buttonRegex) || [];
console.log(`Found ${buttons.length} <button> tags in frontend/index.html`);

const idRegex = /id=["']([^"']+)["']/;
const classRegex = /class=["']([^"']+)["']/;

const buttonAudit = [];

buttons.forEach(btnTag => {
  const idMatch = btnTag.match(idRegex);
  const classMatch = btnTag.match(classRegex);
  buttonAudit.push({
    tag: btnTag,
    id: idMatch ? idMatch[1] : null,
    classes: classMatch ? classMatch[1].split(' ') : []
  });
});

console.log('\nButtons Catalog:');
buttonAudit.forEach((b, idx) => {
  console.log(`[#${idx + 1}] ID: ${b.id || '(no-id)'} | Classes: ${b.classes.join(', ')}`);
});

// Check that each ID or class is referenced in app.js
let missingListeners = 0;
buttonAudit.forEach(b => {
  let isCovered = false;
  if (b.id && (jsContent.includes(`'${b.id}'`) || jsContent.includes(`"${b.id}"`))) {
    isCovered = true;
  }
  if (!isCovered && b.classes.length > 0) {
    for (const cls of b.classes) {
      if (jsContent.includes(cls)) {
        isCovered = true;
        break;
      }
    }
  }
  if (!isCovered) {
    console.error(`⚠️ Unhandled button: ID=${b.id}, Classes=${b.classes.join(' ')}`);
    missingListeners++;
  }
});

if (missingListeners === 0) {
  console.log('\n✅ 100% of all static buttons in index.html are bound to event listeners in app.js!');
} else {
  console.log(`\n❌ Found ${missingListeners} unhandled buttons.`);
}

// Check dynamic buttons generated by app.js:
const dynamicButtons = [
  '.btn-add-pyq-test',
  '.btn-generate-variant',
  '.palette-btn',
  '.latex-option-item',
  '.seat-pod',
  '.mode-card'
];

console.log('\nDynamic Interactive Elements in app.js:');
dynamicButtons.forEach(sel => {
  const isPresent = jsContent.includes(sel);
  console.log(`[Dynamic] ${sel}: ${isPresent ? '✅ Bound' : '❌ Missing'}`);
});
